// Generate all branding artifacts from product/product.yaml (TRD Sec 34, 35).
// Output -> product/generated/ (gitignored, built in CI + before a build).
//
// Usage: node scripts/gen-branding.mjs [--check]
//   --check : validate product.yaml only, write nothing

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseYamlMini } from "./lib/yaml-mini.mjs";
import { validate } from "./lib/validate-mini.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK_ONLY = process.argv.includes("--check");
const OUT = join(ROOT, "product/generated");

const yaml = readFileSync(join(ROOT, "product/product.yaml"), "utf8");
const schema = JSON.parse(readFileSync(join(ROOT, "product/schema/product.schema.json"), "utf8"));

let cfg;
try {
  cfg = parseYamlMini(yaml);
} catch (e) {
  console.error(`✗ product.yaml parse error: ${e.message}`);
  process.exit(1);
}

const errs = validate(schema, cfg);
if (errs.length) {
  console.error("✗ product.yaml invalid:\n  - " + errs.join("\n  - "));
  process.exit(1);
}

// telemetry hard rule (TRD Sec 19)
if (cfg.telemetry && cfg.telemetry.enabled_by_default === true) {
  console.error("✗ telemetry.enabled_by_default must be false (TRD Sec 19)");
  process.exit(1);
}

console.log(`✓ product.yaml valid — ${cfg.product.name} ${cfg.product.version}, ${Object.keys(cfg.apps).length} apps`);
if (CHECK_ONLY) process.exit(0);

mkdirSync(OUT, { recursive: true });
const xmlEsc = (s) => String(s).replace(/[<>&"]/g, (c) => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;" }[c]));
const write = (name, body) => { writeFileSync(join(OUT, name), body); return name; };
const written = [];
const GEN = "Generated by scripts/gen-branding.mjs from product/product.yaml — do not edit.";

// ---- 1. C++ header ---------------------------------------------------------
{
  const appEnum = Object.keys(cfg.apps).map((k) => "    " + k.replace(/^(.)/, (m) => m.toUpperCase())).join(",\n");
  const appName = Object.entries(cfg.apps).map(([k, v]) =>
    `    case App::${k.replace(/^(.)/, (m) => m.toUpperCase())}: return ${JSON.stringify(v.name)};`).join("\n");
  const appId = Object.entries(cfg.apps).map(([k, v]) =>
    `    case App::${k.replace(/^(.)/, (m) => m.toUpperCase())}: return ${JSON.stringify(v.id)};`).join("\n");
  written.push(write("nova_branding.hxx", `// ${GEN}
// SPDX-License-Identifier: MPL-2.0
#pragma once
#include <string_view>

namespace nova::brand {

inline constexpr std::string_view ProductName    = ${JSON.stringify(cfg.product.name)};
inline constexpr std::string_view ProductShort   = ${JSON.stringify(cfg.product.short_name)};
inline constexpr std::string_view Vendor         = ${JSON.stringify(cfg.product.vendor)};
inline constexpr std::string_view Version        = ${JSON.stringify(cfg.product.version)};
inline constexpr std::string_view Copyright      = ${JSON.stringify(cfg.product.copyright ?? "")};
inline constexpr std::string_view HomepageUrl    = ${JSON.stringify(cfg.urls.homepage ?? "")};
inline constexpr std::string_view SupportUrl     = ${JSON.stringify(cfg.urls.support ?? "")};
inline constexpr std::string_view DocsUrl        = ${JSON.stringify(cfg.urls.docs ?? "")};
inline constexpr std::string_view BugReportUrl   = ${JSON.stringify(cfg.urls.bug_report ?? "")};
inline constexpr std::string_view UpdateUrl      = ${JSON.stringify(cfg.endpoints.update ?? "")};
inline constexpr std::string_view TelemetryUrl   = ${JSON.stringify(cfg.endpoints.telemetry ?? "")};
inline constexpr std::string_view RegistryUrl    = ${JSON.stringify(cfg.endpoints.registry ?? "")};
inline constexpr std::string_view CollabServer   = ${JSON.stringify(cfg.endpoints.default_collab_server ?? "")};
inline constexpr std::string_view PrimaryColor   = ${JSON.stringify(cfg.branding.primary_color)};
inline constexpr std::string_view BundleIdPrefix = ${JSON.stringify(cfg.identifiers.bundle_id_prefix)};
inline constexpr std::string_view MimePrefix     = ${JSON.stringify(cfg.identifiers.mime_prefix)};
inline constexpr std::string_view UrlScheme      = ${JSON.stringify(cfg.identifiers.url_scheme)};
inline constexpr bool TelemetryEnabledByDefault  = false;

enum class App {
${appEnum}
};

inline std::string_view AppName(App a) {
  switch (a) {
${appName}
  }
  return ProductName;
}
inline std::string_view AppId(App a) {
  switch (a) {
${appId}
  }
  return {};
}

} // namespace nova::brand
`));
}

// ---- 2. configmgr overlay (org.openoffice.Setup) --------------------------
{
  written.push(write("Nova-Branding.xcu", `<?xml version="1.0" encoding="UTF-8"?>
<!-- ${GEN} -->
<oor:items xmlns:oor="http://openoffice.org/2001/registry"
           xmlns:xs="http://www.w3.org/2001/XMLSchema">
  <item oor:path="/org.openoffice.Setup/Product">
    <prop oor:name="ooName" oor:op="fuse"><value>${xmlEsc(cfg.product.name)}</value></prop>
    <prop oor:name="ooSetupVersion" oor:op="fuse"><value>${xmlEsc(cfg.product.version)}</value></prop>
    <prop oor:name="ooVendor" oor:op="fuse"><value>${xmlEsc(cfg.product.vendor)}</value></prop>
  </item>
  <item oor:path="/org.openoffice.Office.Common/Help">
    <prop oor:name="StartCenterLayoutStyle" oor:op="fuse"><value>1</value></prop>
  </item>
  <item oor:path="/org.openoffice.Office.Common/Menus">
    <prop oor:name="ProductName" oor:op="fuse"><value>${xmlEsc(cfg.product.name)}</value></prop>
  </item>
</oor:items>
`));
}

// ---- 3. runtime JSON (Nova JS / palette / about / server) ----------------
{
  written.push(write("nova-branding.json", JSON.stringify({ _generated: GEN, ...cfg }, null, 2) + "\n"));
}

// ---- 4. Linux .desktop (one per app) ------------------------------------
{
  for (const [key, app] of Object.entries(cfg.apps)) {
    written.push(write(`${app.id}.desktop`, `# ${GEN}
[Desktop Entry]
Type=Application
Version=1.5
Name=${app.name}
GenericName=${cfg.product.description ?? cfg.product.name}
Exec=nova --${key} %U
Icon=${cfg.identifiers.url_scheme}-${key}
Terminal=false
Categories=Office;
StartupNotify=true
X-Nova-App=${app.id}
`));
  }
}

// ---- 5. macOS Info.plist fragment --------------------------------------
{
  const entries = Object.entries(cfg.apps).map(([, a]) =>
    `    <dict>
      <key>CFBundleIdentifier</key><string>${cfg.identifiers.bundle_id_prefix}.${a.id.split(".").pop()}</string>
      <key>CFBundleName</key><string>${a.name}</string>
    </dict>`).join("\n");
  written.push(write("Info.plist.fragment", `<!-- ${GEN} -->
<key>CFBundleName</key><string>${cfg.product.name}</string>
<key>CFBundleShortVersionString</key><string>${cfg.product.version}</string>
<key>CFBundleIdentifier</key><string>${cfg.identifiers.bundle_id_prefix}.app</string>
<key>NSHumanReadableCopyright</key><string>${xmlEsc(cfg.product.copyright ?? "")}</string>
<key>CFBundleURLTypes</key>
<array><dict>
  <key>CFBundleURLName</key><string>${cfg.product.name} URL</string>
  <key>CFBundleURLSchemes</key><array><string>${cfg.identifiers.url_scheme}</string></array>
</dict></array>
<key>NovaApps</key>
<array>
${entries}
</array>
`));
}

// ---- 6. Windows version.rc fragment ----------------------------------
{
  const [maj, min, pat] = cfg.product.version.replace(/-.*/, "").split(".");
  written.push(write("version.rc.fragment", `// ${GEN}
#define NOVA_VER_FILEVERSION      ${maj},${min},${pat},0
#define NOVA_VER_FILEVERSION_STR  "${cfg.product.version}\\0"
#define NOVA_VER_PRODUCTNAME_STR  "${cfg.product.name}\\0"
#define NOVA_VER_COMPANYNAME_STR  "${cfg.product.vendor}\\0"
#define NOVA_VER_LEGALCOPYRIGHT_STR "${(cfg.product.copyright ?? "").replace(/"/g, '\\"')}\\0"
#define NOVA_URL_SCHEME           "${cfg.identifiers.url_scheme}"
`));
}

// ---- 7. MIME type registration -------------------------------------
{
  written.push(write("nova-mimetypes.xml", `<?xml version="1.0" encoding="UTF-8"?>
<!-- ${GEN} -->
<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">
  <mime-type type="${cfg.identifiers.mime_prefix}.notes+zip">
    <comment>${cfg.apps.notes ? cfg.apps.notes.name : "Nova Notes"} document</comment>
    <glob pattern="*.nova"/>
  </mime-type>
</mime-info>
`));
}

// ---- 8. CI banned-literal list ------------------------------------
{
  const banned = [
    cfg.product.name, ...Object.values(cfg.apps).map((a) => a.name),
    cfg.urls.homepage, cfg.urls.support, cfg.urls.docs, cfg.urls.bug_report,
    cfg.endpoints.update, cfg.endpoints.telemetry, cfg.endpoints.registry,
    cfg.endpoints.default_collab_server, cfg.branding.primary_color,
    cfg.identifiers.bundle_id_prefix,
  ].filter((s) => s && s.length > 3);
  written.push(write("banned-literals.json", JSON.stringify({
    _generated: GEN,
    _purpose: "CI greps nova/ and nova-server/ (excluding product/generated/) for these; a hit fails the build (TRD Sec 34).",
    literals: [...new Set(banned)],
  }, null, 2) + "\n"));
}

// ---- 9. LibreOffice configure flags for branding ----------------------
// Verified against the pinned source: the product name/vendor come from
// ./configure, not a config patch (officecfg/Setup.xcu uses ${PRODUCTNAME}).
// scripts/nova-autogen.sh appends these.
//
// autogen.input is "one argument per line", read verbatim by LibreOffice's
// autogen.sh (Perl `read_args`) — no shell parsing, no quote removal. So the
// value must be the *raw* string: `--with-vendor=The Nova-Office contributors`,
// not `--with-vendor='...'`. Wrapping it in quotes put literal `'` characters
// into OOO_VENDOR, which then broke LibreOffice's own single-quoted sed in
// postprocess/CustomTarget_registry.mk ("unterminated `s' command" on main.xcd).
{
  const flagValue = (label, s) => {
    const v = String(s);
    if (v.includes("\n")) throw new Error(`${label} contains a newline — cannot be an autogen.input flag`);
    if (v.startsWith("'") || v.startsWith("#")) throw new Error(`${label} may not start with a quote or '#' (autogen.input parsing)`);
    return v;
  };
  const lines = [
    `# ${GEN}`,
    `--with-product-name=${flagValue("product.name", cfg.product.name)}`,
    `--with-vendor=${flagValue("product.vendor", cfg.product.vendor)}`,
  ];
  const priv = cfg.urls && (cfg.urls.privacy || `${cfg.urls.homepage}/privacy`);
  if (priv) lines.push(`--with-privacy-policy-url=${flagValue("privacy url", priv)}`);
  if (!String(cfg.product.version).includes("-")) lines.push("--enable-release-build");
  written.push(write("nova-configure-flags", lines.join("\n") + "\n"));
}

console.log(`✓ wrote product/generated/: ${written.join(", ")}`);
